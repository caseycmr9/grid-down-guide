/* Service worker: caches every file at install so the whole app works with no connection.
   js/version.js (generated by tools/build.mjs) defines GDG_VERSION and GDG_ASSETS. */
importScripts('js/version.js');

var CACHE = 'gdg-' + self.GDG_VERSION;

self.addEventListener('install', function (event) {
  // Fetch every file with cache: 'reload' so a new version never copies stale files out of the browser's HTTP cache
  // (static hosts such as GitHub Pages send max-age=600).
  event.waitUntil(
    caches.open(CACHE)
      .then(function (cache) {
        return Promise.all(self.GDG_ASSETS.map(function (asset) {
          return fetch(new Request(asset, { cache: 'reload' })).then(function (res) {
            if (!res.ok) throw new Error('Could not cache ' + asset + ' (' + res.status + ')');
            return cache.put(asset, res);
          });
        }));
      })
      .then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys()
      .then(function (keys) {
        return Promise.all(keys.filter(function (k) { return k.indexOf('gdg-') === 0 && k !== CACHE; })
          .map(function (k) { return caches.delete(k); }));
      })
      .then(function () { return self.clients.claim(); })
      .then(function () { return self.clients.matchAll(); })
      .then(function (clients) {
        clients.forEach(function (c) { c.postMessage({ type: 'ready', version: self.GDG_VERSION }); });
      })
  );
});

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') return;
  var url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then(function (hit) {
      if (hit) return hit;
      return fetch(req).catch(function () {
        if (req.mode === 'navigate') return caches.match('index.html');
        return Response.error();
      });
    })
  );
});
