// Build step. Run from the prepper-app folder:   node tools/build.mjs
//  1. validates all content
//  2. wires every data/*.js file into index.html
//  3. generates js/version.js (version stamp + list of files the service worker caches)
//  4. writes docs/        (upload this folder to any static host -> installable offline PWA)
//     and  dist/grid-down-guide.html   (ONE self-contained file: works from a USB stick / SD card / file manager)
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';

const root = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const P = (...a) => path.join(root, ...a);
const read = (p) => fs.readFileSync(P(p), 'utf8');
const force = process.argv.includes('--force');

// 1. validate
const v = spawnSync(process.execPath, [P('tools', 'validate.mjs'), '--all'], { encoding: 'utf8' });
const tail = v.stdout.trim().split('\n').slice(-6).join('\n');
console.log(tail);
if (v.status !== 0 && !force) { console.error('\nValidation failed. Fix errors (or use --force).'); process.exit(1); }

// 2. data files in category order
const win = {};
vm.runInContext(read('data/categories.js'), vm.createContext({ window: win }));
const order = win.CATEGORIES.map((c) => c.id);
const dataFiles = fs.readdirSync(P('data')).filter((f) => f.endsWith('.js') && f !== 'categories.js' && !f.startsWith('_'));
dataFiles.sort((a, b) => {
  const ia = order.indexOf(a.replace(/\.js$/, '')), ib = order.indexOf(b.replace(/\.js$/, ''));
  return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib) || a.localeCompare(b);
});
let html = read('index.html');
const block = dataFiles.map((f) => `<script src="data/${f}"></script>`).join('\n');
html = html.replace(/<!--DATA:START-->[\s\S]*?<!--DATA:END-->/, `<!--DATA:START-->\n${block}\n<!--DATA:END-->`);
fs.writeFileSync(P('index.html'), html);

// 3. asset list + version
const assets = ['./', 'index.html', 'manifest.webmanifest', 'css/style.css', 'js/version.js', 'js/md.js', 'js/tools.js', 'js/app.js',
  'data/categories.js', ...dataFiles.map((f) => 'data/' + f), 'icons/icon.svg', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/apple-touch-icon.png']
  .filter((a) => a === './' || a === 'js/version.js' || fs.existsSync(P(a))); // version.js is written just below
const hash = crypto.createHash('sha1');
for (const a of [...assets.filter((x) => x !== './' && x !== 'js/version.js'), 'sw.js']) hash.update(fs.readFileSync(P(a)));
const d = new Date();
const stamp = `${d.getFullYear()}${String(d.getMonth() + 1).padStart(2, '0')}${String(d.getDate()).padStart(2, '0')}`;
const version = `${stamp}-${hash.digest('hex').slice(0, 8)}`;
fs.writeFileSync(P('js', 'version.js'),
  `/* generated by tools/build.mjs: do not edit */\n(function (g) { g.GDG_VERSION = '${version}'; g.GDG_ASSETS = ${JSON.stringify(assets)}; })(typeof self !== 'undefined' ? self : window);\n`);
console.log(`\nVersion ${version}: ${assets.length} cached files`);

// 4a. docs/  (the installable site; GitHub Pages serves this folder, or upload it to any static host)
const dist = P('dist');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });
const site = P('docs');
fs.rmSync(site, { recursive: true, force: true });
fs.mkdirSync(site, { recursive: true });
fs.writeFileSync(path.join(site, '.nojekyll'), '');
for (const a of [...assets.filter((x) => x !== './'), 'sw.js']) {
  fs.mkdirSync(path.dirname(path.join(site, a)), { recursive: true });
  fs.copyFileSync(P(a), path.join(site, a));
}

// 4b. single-file build
let single = read('index.html');
const safe = (s) => s.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
single = single.replace(/<link rel="manifest"[^>]*>\s*/g, '').replace(/<link rel="apple-touch-icon"[^>]*>\s*/g, '');
if (fs.existsSync(P('icons/icon.svg'))) {
  const svg = encodeURIComponent(read('icons/icon.svg')).replace(/'/g, '%27');
  single = single.replace(/<link rel="icon"[^>]*>/, `<link rel="icon" href="data:image/svg+xml,${svg}">`);
}
single = single.replace(/<link rel="stylesheet" href="([^"]+)">/g, (m, href) => `<style>\n${read(href)}\n</style>`);
single = single.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => `<script>\n${safe(read(src))}\n</script>`);
fs.writeFileSync(path.join(dist, 'grid-down-guide.html'), single);
fs.writeFileSync(path.join(site, 'grid-down-guide.html'), single); // downloadable backup copy served next to the app (not part of the offline cache)

const kb = (n) => (n / 1024).toFixed(0) + ' KB';
console.log(`docs/                         ${kb(assets.reduce((n, a) => n + (a === './' ? 0 : fs.statSync(P(a)).size), 0))} (host this folder)`);
console.log(`dist/grid-down-guide.html     ${kb(fs.statSync(path.join(dist, 'grid-down-guide.html')).size)} (single offline file)`);
