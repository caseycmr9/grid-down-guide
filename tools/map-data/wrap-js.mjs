// Wrap an out/*.json file as a lazy-loadable script: window.GDG_MAP.<part> = {...}
import fs from 'node:fs';
const [,, part, inFile, outFile, metaJson] = process.argv;
const data = fs.readFileSync(inFile, 'utf8');
let js = '/* Grid Down Guide map data: generated by tools/map-data, do not edit */\n(window.GDG_MAP = window.GDG_MAP || {});\n';
if (metaJson) js += 'window.GDG_MAP.meta = ' + metaJson + ';\n';
js += 'window.GDG_MAP.' + part + ' = ' + data + ';\n';
fs.mkdirSync(outFile.replace(/[\/][^\/]*$/, ''), { recursive: true });
fs.writeFileSync(outFile, js);
console.log(outFile, js.length, 'bytes');
